#!/usr/bin/env python3
"""
Turn the movement's content into the block markup WordPress stores for a page.

Addresses are written root-relative — /about/, not https://…/about/ — so the
same content works on the temporary host and on nationaldayofprayer.eu without
a single link being rewritten when the domain changes.

    python3 build.py        # writes pages/*.html
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CONTENT = ROOT.parent / "content"
OUT = ROOT / "pages"

sys.path.insert(0, str(ROOT))


THEME_FILES = "/wp-content/themes/ndop/assets/"


def url(target):
    """
    Address of anything the site links to.

    A page becomes /about/. A file that travels with the theme — the brochure —
    becomes its path inside the theme. Both are root-relative, so the move from
    the temporary host to nationaldayofprayer.eu rewrites nothing.
    """
    if target.startswith("assets/"):
        return THEME_FILES + target[len("assets/"):]

    anchor = ""
    if "#" in target:
        target, anchor = target.split("#", 1)
        anchor = "#" + anchor

    slug = target.replace(".html", "").strip("/")
    base = "/" if slug in ("", "index") else f"/{slug}/"
    return base + anchor


def load(name):
    return json.loads((CONTENT / f"{name}.json").read_text(encoding="utf-8"))


def main():
    import pages_home, pages_about, pages_history
    import pages_resources, pages_faq, pages_contact

    builders = {
        "index":     pages_home.build,
        "about":     pages_about.build,
        "history":   pages_history.build,
        "resources": pages_resources.build,
        "faq":       pages_faq.build,
        "contact":   pages_contact.build,
    }

    write_meta(builders)
    write_captions()

    OUT.mkdir(exist_ok=True)
    for slug, build in builders.items():
        content = load(slug)
        markup = build(content, url)
        (OUT / f"{slug}.html").write_text(markup, encoding="utf-8")
        print(f"  {slug:<10} {len(markup):>7,} байт")

    print(f"\nГотово: {len(builders)} сторінк(и) у {OUT}")


def php_string(value):
    """A single-quoted PHP string."""
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def write_captions():
    """
    The line that appears under a photograph when it is opened full size.

    These travel with the picture rather than with the page: the theme writes
    each one into the media library as that image's caption, so the client can
    change it where the photograph itself lives, and a photograph swapped for
    another keeps a sensible line of its own.
    """
    captions = {}

    history = load("history")
    for e in history["entries"]:
        if e.get("caption"):
            captions[e["image"].split("/")[-1]] = e["caption"]
        if e.get("extraImage") and e.get("extraCaption"):
            captions[e["extraImage"].split("/")[-1]] = e["extraCaption"]

    res = load("resources")
    for img_key, cap_key in (("lawScanImage", "lawScanCaption"), ("uaImage", "uaCaption")):
        if res.get(img_key) and res.get(cap_key):
            captions[res[img_key].split("/")[-1]] = res[cap_key]

    rows = "\n".join(
        "\t\t{} => {},".format(php_string(k).ljust(28), php_string(v))
        for k, v in sorted(captions.items())
    )

    php = """<?php
/**
 * Captions for the photographs that open full size.
 *
 * Generated by wp-theme/build.py — do not edit by hand. The theme copies each
 * one into the media library when it imports the picture, and reads it back
 * from there when the page is rendered.
 */

if ( ! defined( 'ABSPATH' ) ) {{
	exit;
}}

/** File name in assets/img => the caption shown beneath the enlarged picture. */
function ndop_caption_map() {{
	return array(
{rows}
	);
}}
""".format(rows=rows)

    (ROOT / "ndop" / "inc" / "captions.php").write_text(php, encoding="utf-8")
    print(f"  {'captions.php':<12} {len(captions)} \u043f\u0456\u0434\u043f\u0438\u0441\u0456\u0432")


def write_meta(builders):
    """
    The exact <title> and description of each page, as the site has always
    carried them.

    WordPress would otherwise compose its own — "About Us – site name" — and the
    wording that was written for search results would be lost. They are written
    out here rather than typed into the theme so that the two can never drift.
    """
    rows = []
    for slug in builders:
        c = load(slug)
        rows.append(
            "\t\t{}=> array(\n\t\t\t'title'       => {},\n\t\t\t'description' => {},\n\t\t),".format(
                php_string(slug).ljust(13),
                php_string(c["title"]),
                php_string(c["description"]),
            )
        )

    php = """<?php
/**
 * The words that appear in a search result.
 *
 * Generated by wp-theme/build.py from the movement's content — do not edit by
 * hand, the next build overwrites it. Keeping these here means a page's title
 * stays what it was written to be instead of what WordPress would assemble.
 */

if ( ! defined( 'ABSPATH' ) ) {{
	exit;
}}

/** Slug => the page's own title and description. */
function ndop_meta_map() {{
	return array(
{rows}
	);
}}
""".format(rows="\n".join(rows))

    (ROOT / "ndop" / "inc" / "meta.php").write_text(php, encoding="utf-8")
    print(f"  {'meta.php':<10} {len(php):>7,} байт")


if __name__ == "__main__":
    main()
